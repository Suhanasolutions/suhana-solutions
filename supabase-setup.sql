-- SUHANA SOLUTIONS: Supabase setup for the separate admin portal
-- Run in Supabase Dashboard > SQL Editor.
-- Then create your own user in Authentication > Users and insert that user's UUID
-- into public.admin_users using the final statement below.

create table if not exists public.service_requests (
  id bigint generated by default as identity primary key,
  full_name text not null,
  phone text not null,
  business_name text,
  service_type text not null,
  message text,
  status text not null default 'New',
  created_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.business_transactions (
  id bigint generated by default as identity primary key,
  transaction_date date not null default current_date,
  transaction_type text not null check (transaction_type in ('income','expense','purchase')),
  category text not null,
  amount numeric(12,2) not null check (amount > 0),
  description text,
  payment_status text not null default 'paid' check (payment_status in ('paid','pending')),
  created_at timestamptz not null default now()
);

-- Optional operational tables used by the admin overview.
create table if not exists public.job_applications (
  id bigint generated by default as identity primary key,
  full_name text not null,
  phone text not null,
  email text,
  role_applied text,
  message text,
  status text not null default 'New',
  created_at timestamptz not null default now()
);

create table if not exists public.staff_requests (
  id bigint generated by default as identity primary key,
  business_name text,
  contact_name text not null,
  phone text not null,
  role_needed text not null,
  quantity integer not null default 1 check (quantity > 0),
  message text,
  status text not null default 'New',
  created_at timestamptz not null default now()
);

create table if not exists public.staff_members (
  id bigint generated by default as identity primary key,
  full_name text not null,
  role text not null,
  monthly_salary numeric(12,2) not null default 0 check (monthly_salary >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.service_requests enable row level security;
alter table public.admin_users enable row level security;
alter table public.business_transactions enable row level security;

alter table public.job_applications enable row level security;
alter table public.staff_requests enable row level security;
alter table public.staff_members enable row level security;

-- These tables are private by default; only authorised admins can read them.
drop policy if exists "Admins can read job applications" on public.job_applications;
create policy "Admins can read job applications" on public.job_applications
for select to authenticated
using (exists (select 1 from public.admin_users au where au.user_id = auth.uid()));

drop policy if exists "Admins can read staff requests" on public.staff_requests;
create policy "Admins can read staff requests" on public.staff_requests
for select to authenticated
using (exists (select 1 from public.admin_users au where au.user_id = auth.uid()));

drop policy if exists "Admins can read staff members" on public.staff_members;
create policy "Admins can read staff members" on public.staff_members
for select to authenticated
using (exists (select 1 from public.admin_users au where au.user_id = auth.uid()));


-- Public visitors may submit requests only; they cannot read customer requests.
drop policy if exists "Public can submit service requests" on public.service_requests;
create policy "Public can submit service requests"
on public.service_requests for insert to anon, authenticated
with check (
  length(trim(full_name)) between 1 and 120
  and length(trim(phone)) between 8 and 24
  and length(trim(service_type)) between 1 and 120
);

-- A signed-in account is an admin only if its UUID is listed in admin_users.
drop policy if exists "Admins can verify own membership" on public.admin_users;
create policy "Admins can verify own membership"
on public.admin_users for select to authenticated
using (user_id = auth.uid());

drop policy if exists "Admins can read service requests" on public.service_requests;
create policy "Admins can read service requests"
on public.service_requests for select to authenticated
using (exists (select 1 from public.admin_users au where au.user_id = auth.uid()));

drop policy if exists "Admins can read transactions" on public.business_transactions;
create policy "Admins can read transactions"
on public.business_transactions for select to authenticated
using (exists (select 1 from public.admin_users au where au.user_id = auth.uid()));

drop policy if exists "Admins can add transactions" on public.business_transactions;
create policy "Admins can add transactions"
on public.business_transactions for insert to authenticated
with check (exists (select 1 from public.admin_users au where au.user_id = auth.uid()));

grant select on public.job_applications to authenticated;
grant select on public.staff_requests to authenticated;
grant select on public.staff_members to authenticated;

grant insert on public.service_requests to anon, authenticated;
grant select on public.service_requests to authenticated;
grant select on public.admin_users to authenticated;
grant select, insert on public.business_transactions to authenticated;
grant usage, select on sequence public.service_requests_id_seq to anon, authenticated;
grant usage, select on sequence public.business_transactions_id_seq to authenticated;

